"""Build the Zenvix WordPress theme from the same templates as the static site.

Usage:  python3 _build/build_wp.py
Output: wordpress/zenvix/          (theme folder)
        wordpress/zenvix-theme.zip (upload via Appearance → Themes → Add New → Upload)

Static page bodies (home, about, services, contact, 404) are rendered by pages.py and converted to PHP:
links become zx_url() calls, assets point to the theme folder and contact details come from the
Zenvix Settings page. Hand-written PHP (blog, settings, SEO, Contact Form 7, setup) lives in _build/wp/.
"""
import json
import os
import re
import shutil
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

import layout  # noqa: E402
import pages  # noqa: E402
from layout import SITE  # noqa: E402
from services_data import SERVICES  # noqa: E402

TOKEN = "@@ROOT@@/"
OUT = os.path.join(ROOT, "wordpress", "zenvix")
SRC = os.path.join(HERE, "wp")


# ---------------------------------------------------------------- converters
def php_links(html):
    """@@ROOT@@ links → theme asset URLs and WordPress page/post URLs."""
    html = html.replace(TOKEN + "assets/", "<?php echo esc_url( ZX_URI ); ?>/assets/")
    html = html.replace(TOKEN + "favicon.ico", "<?php echo esc_url( ZX_URI ); ?>/favicon.ico")

    def repl(m):
        path, frag = m.group(1), m.group(2) or ""
        if path == "index":
            key = ""
        elif path.startswith("blog/"):
            key = "post:" + path[5:]
        else:
            key = path
        return f"<?php echo esc_url( zx_url( '{key}' ) ); ?>{frag}"

    html = re.sub(r"@@ROOT@@/([a-z0-9\-/]+)\.html(#[\w-]+)?", repl, html)
    assert TOKEN not in html, "unconverted link: " + html[html.index(TOKEN) - 60: html.index(TOKEN) + 80]
    return html


def php_contact(html):
    """Hard-coded contact details → values from the Zenvix Settings page."""
    e = lambda k: f"<?php zx_e( '{k}' ); ?>"  # noqa: E731
    u = lambda k: f"<?php zx_eu( '{k}' ); ?>"  # noqa: E731
    pairs = [
        ("tel:" + SITE["phone_href"], "tel:" + e("phone_href")),
        (SITE["whatsapp"], u("whatsapp_url")),
        (SITE["map_embed"], u("map_embed")),
        (SITE["map"], u("map_url")),
        (SITE["email"], e("email")),
        (SITE["phone"], e("phone")),
        (SITE["hours"], e("hours")),
        ("Gulberg, Lahore,<br>Punjab, Pakistan", e("address_1") + ",<br>" + e("address_2")),
        ("Gulberg, Lahore, Punjab, Pakistan", e("address_1") + ", " + e("address_2")),
        ("Gulberg, Lahore · Serving clients worldwide", e("address_1") + " · Serving clients worldwide"),
        ("Gulberg, Lahore, Pakistan", e("address_1") + ", " + e("address_2")),
    ]
    for a, b in pairs:
        html = html.replace(a, b)
    keys = {"Facebook": "facebook", "Instagram": "instagram", "X": "x", "LinkedIn": "linkedin"}
    html = re.sub(r'<a href="#" aria-label="((?:Zenvix on )?(Facebook|Instagram|X|LinkedIn))"',
                  lambda m: f'<a href="{u(keys[m.group(2)])}" aria-label="{m.group(1)}"', html)
    return html


def to_php(html):
    return php_contact(php_links(html))


def write(rel, content):
    full = os.path.join(OUT, rel)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w", encoding="utf-8") as f:
        f.write(content)


def template(rel, body, note):
    write(rel, f"<?php\n/**\n * {note}\n * Generated by _build/build_wp.py — edit the Python templates, not this file.\n */\nget_header();\n?>\n{to_php(body)}\n<?php get_footer();\n")


# ---------------------------------------------------------------- header / footer
def build_header_footer():
    page = {"root": TOKEN, "nav": "", "path": "footer", "body": ""}
    h = layout.header(page)
    h = h.replace('<body class="">', "<body <?php body_class(); ?>>\n<?php wp_body_open(); ?>", 1)
    h = re.sub(r'(<a href="@@ROOT@@/(index|about|services|blog|contact)\.html")>(Home|About|Services|Blog|Contact)',
               lambda m: f"{m.group(1)}<?php zx_nav_class( '{m.group(2).replace('index', 'home')}' ); ?>>{m.group(3)}", h)
    head = """<?php
/**
 * Site header. Generated by _build/build_wp.py — edit _build/layout.py, not this file.
 */
?><!doctype html>
<html <?php language_attributes(); ?>>
<head>
<meta charset="<?php bloginfo( 'charset' ); ?>">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<meta name="theme-color" content="#7c3aed">
<script>document.documentElement.classList.add("js")</script>
<?php wp_head(); ?>
</head>
"""
    write("header.php", head + to_php(h) + "\n")

    f = layout.footer(page)
    f = re.sub(r'<script src="@@ROOT@@/assets/js/main\.js\?v=1" defer></script>', "<?php wp_footer(); ?>", f)
    write("footer.php", "<?php\n/**\n * Site footer. Generated by _build/build_wp.py — edit _build/layout.py, not this file.\n */\n?>\n" + to_php(f) + "\n")


# ---------------------------------------------------------------- pages
SEO = {}


def collect_seo(key, page):
    schemas = []
    for s in page.get("schema", []):
        if s.get("@type") in ("ProfessionalService", "Blog"):
            continue  # organization schema is built from settings; blog list is dynamic
        js = json.dumps(s, ensure_ascii=False)
        js = re.sub(r"https://zenvixtechnologies\.com/([a-z0-9\-/]*?)\.html", r"{{HOME}}/\1/", js)
        js = js.replace("{{HOME}}/index/", "{{HOME}}/").replace("https://zenvixtechnologies.com", "{{HOME}}")
        schemas.append(json.loads(js))
    SEO[key] = {"title": page["title"], "desc": page["desc"], "og": page.get("og", "assets/img/og-image.jpg"),
                "body": page.get("body", ""), "schema": schemas, "preload": bool(page.get("preload"))}


def with_root(fn, *a):
    """Render a page builder with links/assets based on TOKEN instead of relative paths."""
    page, body = fn(*a)
    root = page["root"]
    if root == "../":
        body = body.replace('="../', '="' + TOKEN)
    elif root == "/":
        body = re.sub(r'href="/(index|contact)\.html"', lambda m: f'href="{TOKEN}{m.group(1)}.html"', body)
    else:
        body = re.sub(r'(href|src)="(?!https?:|mailto:|tel:|#|/|data:)([^"]+)"', lambda m: f'{m.group(1)}="{TOKEN}{m.group(2)}"', body)
        body = re.sub(r'(srcset)="(?!https?:)([^"]+)"', lambda m: f'{m.group(1)}="{TOKEN}{m.group(2)}"', body)
    return page, body


def build_pages(blogs):
    # Home: latest posts come from WordPress
    page, body = with_root(pages.home, blogs)
    body, n = re.subn(r'(<section class="section" id="blog">.*?<div class="grid-3">).*?(</div>\s*<div class="center mt-40 reveal">)',
                      r"\1<?php zx_latest_posts( 3 ); ?>\2", body, count=1, flags=re.S)
    assert n == 1
    collect_seo("front", page)
    template("front-page.php", body, "Front page (Home).")

    page, body = with_root(pages.about)
    collect_seo("about", page)
    template("page-about.php", body, "About page (slug: about).")

    page, body = with_root(pages.services_overview)
    collect_seo("services", page)
    template("page-services.php", body, "Services overview (slug: services).")

    # Contact: Contact Form 7 replaces the static form
    page, body = with_root(pages.contact)
    body, n = re.subn(r'<form class="contact-form" novalidate data-contact-form>.*?</form>', "<?php zx_contact_form(); ?>", body, count=1, flags=re.S)
    assert n == 1
    body, n = re.subn(r"<h2>Almost there!</h2>.*?<p class=\"muted\">.*?</p>",
                      "<h2>Message sent!</h2>\n        <p>Thank you for reaching out. We've received your message and our team will get back to you within <strong>24 hours</strong>.</p>\n"
                      "        <p class=\"muted\">In the meantime, feel free to explore our work or read our blog.</p>", body, count=1, flags=re.S)
    assert n == 1
    collect_seo("contact", page)
    template("page-contact.php", body, "Contact page (slug: contact).")

    for s in SERVICES:
        page, body = with_root(pages.service_page, s, blogs)
        collect_seo(s["slug"], page)
        template(f"page-{s['slug']}.php", body, f"Service page: {s['name']} (slug: services/{s['slug']}).")

    page, body = with_root(pages.not_found)
    collect_seo("404", page)
    template("404.php", body, "404 page.")

    # Blog list: reuse the newsletter + topics block below the grid
    page, body = with_root(pages.blog_list, blogs)
    collect_seo("blog", page)
    extras = re.search(r'(<section class="section-sm">\s*<div class="container">\s*<div class="newsletter-band.*?</section>)', body, re.S).group(1)
    write("template-parts/blog-extras.php", "<?php\n/** Newsletter + topics band below the blog grid. Generated by _build/build_wp.py. */\n?>\n" + to_php(extras) + "\n")

    write("inc/seo-data.php", "<?php\n/** Per-page SEO data. Generated by _build/build_wp.py. */\nreturn json_decode( <<<'JSON'\n"
          + json.dumps(SEO, ensure_ascii=False, indent=1) + "\nJSON\n, true );\n")


# ---------------------------------------------------------------- demo blog posts
def build_posts(blogs):
    posts = []
    for b in blogs:
        html = pages.localize_links(b["html"], TOKEN)
        html = re.sub(r'<h2 id="sources-and-notes">.*?</h2>', "", html)
        srcs = "".join(f'<li><a href="{u}" target="_blank" rel="nofollow noopener">{u.split("//")[-1].split("/")[0]}</a></li>'
                       for u in b["sources"] if u.startswith("http"))
        if srcs:
            html += f'\n<details class="sources"><summary>Sources &amp; notes</summary><ul>{srcs}</ul></details>'
        html = re.sub(r"@@ROOT@@/([a-z0-9\-/]+)\.html",
                      lambda m: "{{url:" + ("post:" + m.group(1)[5:] if m.group(1).startswith("blog/") else ("" if m.group(1) == "index" else m.group(1))) + "}}", html)
        assert TOKEN not in html
        posts.append({"slug": b["slug"], "title": b["title"], "excerpt": b["excerpt"], "date": b["date"] + " 10:00:00",
                      "category": b["cat"], "tags": b["tags"], "image": b["img"], "content": html})
    write("inc/demo/posts.json", json.dumps(posts, ensure_ascii=False, indent=1))


# ---------------------------------------------------------------- assemble
def main():
    blogs = pages.load_blogs()
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    shutil.copytree(SRC, OUT)
    shutil.copytree(os.path.join(ROOT, "assets"), os.path.join(OUT, "assets"), dirs_exist_ok=True)
    shutil.copy(os.path.join(ROOT, "favicon.ico"), os.path.join(OUT, "favicon.ico"))
    build_header_footer()
    build_pages(blogs)
    build_posts(blogs)
    try:  # theme screenshot (1200x900)
        from PIL import Image
        im = Image.open(os.path.join(ROOT, "assets/img/og-image.jpg")).convert("RGB")
        canvas = Image.new("RGB", (1200, 900), (246, 245, 249))
        canvas.paste(im, (0, 135))
        canvas.save(os.path.join(OUT, "screenshot.png"), optimize=True)
    except Exception as exc:  # pragma: no cover
        print("screenshot skipped:", exc)
    zpath = os.path.join(ROOT, "wordpress", "zenvix-theme.zip")
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for base, _, files in os.walk(OUT):
            for fn in files:
                if fn == ".DS_Store":
                    continue
                full = os.path.join(base, fn)
                z.write(full, os.path.join("zenvix", os.path.relpath(full, OUT)))
    print("Theme built:", OUT)
    print("Zip:", zpath, f"({os.path.getsize(zpath) // 1024} KB)")


if __name__ == "__main__":
    main()
